-- Do NOT expose the database connection string to the browser.
CREATE TABLE IF NOT EXISTS public.vehicles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand TEXT NOT NULL, model TEXT NOT NULL, year INTEGER NOT NULL,
  km INTEGER NOT NULL, price NUMERIC(14,2) NOT NULL,
  category TEXT NOT NULL, fuel TEXT NOT NULL, transmission TEXT NOT NULL,
  color TEXT NOT NULL, power TEXT NOT NULL, tag TEXT NOT NULL,
  image TEXT NOT NULL, description TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'disponivel' CHECK (status IN ('disponivel','reservado','vendido','rascunho')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.leads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_id BIGINT REFERENCES public.vehicles(id) ON DELETE SET NULL,
  name TEXT NOT NULL, phone TEXT NOT NULL, interest TEXT NOT NULL,
  scheduled_for TEXT, consent INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'novo', created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.proposals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL, phone TEXT NOT NULL, car TEXT NOT NULL, details TEXT,
  consent INTEGER NOT NULL DEFAULT 0, status TEXT NOT NULL DEFAULT 'novo',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL, email TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.customer_sessions (
  token_hash TEXT PRIMARY KEY, customer_id BIGINT NOT NULL REFERENCES public.customers(id) ON DELETE CASCADE,
  expires BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS public.admins (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS public.sessions (
  token_hash TEXT PRIMARY KEY, admin_id BIGINT NOT NULL REFERENCES public.admins(id) ON DELETE CASCADE,
  expires BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS public.audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id BIGINT REFERENCES public.admins(id) ON DELETE SET NULL,
  action TEXT NOT NULL, target TEXT NOT NULL, target_id BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_vehicles_status ON public.vehicles(status);
CREATE INDEX IF NOT EXISTS idx_leads_vehicle_id ON public.leads(vehicle_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expires ON public.sessions(expires);
CREATE INDEX IF NOT EXISTS idx_customer_sessions_expires ON public.customer_sessions(expires);
